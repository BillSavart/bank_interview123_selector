/** 招考階段：筆試 / 面試。 */
export type VenueStage = 'written' | 'interview';

export interface VenueSession {
  /** 試場名稱，例如「第 1 試場」。 */
  room: string;
  /** 報考職等，例如「兆八」「兆六」；面試常用，筆試可省略。 */
  grade?: string;
  /** 缺考人數（0 代表無缺考、也會顯示；不知道就省略）。 */
  absent?: number;
  /** 面試題目 / 考驗重點；筆試通常沒有，可省略。 */
  questions?: string[];
  /** 該試場的其他備註，可省略。 */
  note?: string;
}

export interface VenueReport {
  /** 穩定的唯一 id（也用於網址 hash 定位）。 */
  id: string;
  /** 銀行名稱，例如「兆豐銀行」。 */
  bank: string;
  /** 階段：'written' 筆試 / 'interview' 面試。 */
  stage: VenueStage;
  /** 招考 / 面試日期（YYYY-MM-DD）。 */
  date: string;
  /** 各試場資訊。 */
  sessions: VenueSession[];
  /** 沒有明確標示試場、但值得參考的零散考題（多用於面試）。 */
  extras?: string[];
  /** 資料來源 / 整理備註，可省略。 */
  note?: string;
}

